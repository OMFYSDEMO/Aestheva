// Builds seed/dev-sample.sql from the prototype's fictional catalogue, for local development and tests.
// Never load it into production: real providers join through onboarding and verification.
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'prototype/data.js'), 'utf8'), ctx);
const D = ctx.window.AE_DATA;

const q = v => v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const row = vals => `(${vals.map(q).join(', ')})`;
const slug = s => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const toMin = t => { const [h, m] = t.split(':').map(Number); return h * 60 + m; };
const LIVE = { p1: '2026-08-03', p2: '2026-08-03', p3: '2026-09-07', p4: '2026-08-03', p5: '2026-08-24', p6: '2026-09-14', p7: '2026-08-10', p8: '2026-10-06' };

const out = ['-- Generated by scripts/build-dev-seed.mjs from prototype/data.js. Fictional sample data: development and tests only.'];
out.push('INSERT INTO providers (id, slug, name, type, area, address, tagline, about, hours_text, amenities_json, art, status, live_since) VALUES\n' +
  D.providers.map(p => row([p.id, slug(p.name), p.name, p.type, p.area, p.address, p.tagline, p.about, p.hours, JSON.stringify(p.amenities), p.art, 'live', LIVE[p.id]])).join(',\n') + ';');
const ver = []; D.providers.forEach(p => p.verification.forEach((v, i) => ver.push(row([p.id, v.label, v.scope, v.date, i]))));
out.push('INSERT INTO verifications (provider_id, label, scope, checked_on, sort) VALUES\n' + ver.join(',\n') + ';');
out.push('INSERT INTO staff (id, provider_id, name, role, medical, quals_json, registration, years, langs_json, bio) VALUES\n' +
  D.staff.map(s => row([s.id, s.providerId, s.name, s.role, s.medical ? 1 : 0, JSON.stringify(s.quals), s.reg, s.years, JSON.stringify(s.langs), s.bio])).join(',\n') + ';');
const hours = []; D.staff.forEach(s => s.avail.days.forEach(d => hours.push(row([s.id, d, toMin(s.avail.start), toMin(s.avail.end)]))));
out.push('INSERT INTO staff_hours (staff_id, dow, start_min, end_min) VALUES\n' + hours.join(',\n') + ';');
out.push('INSERT INTO services (id, provider_id, name, cat, kind, dur_min, price_paise, deposit_paise, description, sort) VALUES\n' +
  D.services.map((s, i) => row([s.id, s.providerId, s.name, s.cat, s.kind, s.dur, s.price * 100, s.deposit * 100, s.desc, i])).join(',\n') + ';');
const ss = []; D.services.forEach(s => s.staff.forEach(st => ss.push(row([s.id, st]))));
out.push('INSERT INTO service_staff (service_id, staff_id) VALUES\n' + ss.join(',\n') + ';');
out.push('INSERT INTO reviews (provider_id, staff_id, author, rating, service_name, body, created_on) VALUES\n' +
  D.reviews.map(r => row([r.providerId, r.staffId, r.name, r.rating, r.service, r.text, r.date])).join(',\n') + ';');

fs.mkdirSync(path.join(root, 'seed'), { recursive: true });
fs.writeFileSync(path.join(root, 'seed/dev-sample.sql'), out.join('\n\n') + '\n');
console.log(`seed/dev-sample.sql: ${D.providers.length} providers, ${D.staff.length} staff, ${D.services.length} services, ${D.reviews.length} reviews`);
